/* ============================================================
   project.js: renders a project write-up from markdown.

   Page shell:  projects/<slug>/index.html   (generated by scripts/prerender-projects.js)
   Content:     projects/<slug>/index.md     (you write this)
   Styles:      projects/project.css
   Diagrams:    projects/diagram.js          (window.D)

   Markdown additions on top of normal GitHub-flavoured markdown
   (see projects/_template/index.md for a working example):

     ## Heading {#custom-id}      h2 becomes a table-of-contents entry; {#id} is optional
     ##### Label                  small bold label (the "Flow" / "Explanation" lines)
     1. step                      ordered lists render as the numbered "flow" list
     ```py path/to/file.py        code block with a file-name caption above it
     ```diagram                   hand-drawn diagram (id / size / alt / caption, ---, spec)
     :::qa Question? ... :::      collapsible Q&A
     :::gaps ... :::              "Trade-offs and gaps" call-out box
     :::note ... :::              small grey note paragraph
     :::table stack 17% 38% ...   table with a class and column widths (optional)
   ============================================================ */

(function () {
  "use strict";

  var PROJECTS_DIR = "/projects/"; // absolute: must work at any page depth
  var SITE_NAME = "Arpon Kapuria";

  /* ---------------- Small helpers ---------------- */
  function parseFrontmatter(raw) {
    var m = raw.match(/^---\s*\n([\s\S]*?)\n---\s*\n?/);
    if (!m) return { meta: {}, body: raw };
    var meta = {};
    m[1].split("\n").forEach(function (line) {
      var idx = line.indexOf(":");
      if (idx === -1) return;
      var key = line.slice(0, idx).trim();
      var val = line.slice(idx + 1).trim();
      if (/^\[.*\]$/.test(val)) {
        val = val.slice(1, -1).split(",").map(function (s) {
          return s.trim().replace(/^["']|["']$/g, "");
        }).filter(Boolean);
      } else {
        val = val.replace(/^["']|["']$/g, "");
      }
      meta[key] = val;
    });
    return { meta: meta, body: raw.slice(m[0].length) };
  }

  function escapeHtml(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }

  function escapeCode(s) {
    return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  }

  function slugify(text) {
    return text.toLowerCase().trim().replace(/[^\w\s-]/g, "").replace(/\s+/g, "-");
  }

  function getSlug() {
    if (window.__PROJECT_SLUG__) return window.__PROJECT_SLUG__;
    var m = window.location.pathname.match(/\/projects\/([^/]+)/);
    return m ? m[1] : null;
  }

  /* ---------------- Diagram blocks ----------------
     ```diagram
     id: d-system          (needed; it also seeds the sketchy wobble, so keep it stable)
     size: 920 672
     alt: text for screen readers
     caption: text under the figure
     ---
     { groups: [...], nodes: [...], edges: [...], notes: [...] }
     ```                                                                      */
  var diagrams = [];

  function diagramHtml(code) {
    var lines = code.split("\n");
    var sep = lines.findIndex(function (l) { return l.trim() === "---"; });
    var head = {};
    (sep === -1 ? [] : lines.slice(0, sep)).forEach(function (line) {
      var i = line.indexOf(":");
      if (i > -1) head[line.slice(0, i).trim()] = line.slice(i + 1).trim();
    });
    var size = (head.size || "").split(/[\sx,]+/).map(Number);
    if (!head.id || !(size[0] > 0) || !(size[1] > 0) || sep === -1) {
      return '<p class="note">Diagram block needs <code>id</code>, <code>size</code> and a <code>---</code> line before the spec.</p>';
    }
    diagrams.push({ id: head.id, w: size[0], h: size[1], spec: lines.slice(sep + 1).join("\n") });
    return '<figure class="fig"><div class="scroll"><div id="' + escapeHtml(head.id) +
      '" data-alt="' + escapeHtml(head.alt || "") + '"></div></div>' +
      (head.caption ? "<figcaption>" + marked.parseInline(head.caption) + "</figcaption>" : "") +
      "</figure>\n";
  }

  /* ---------------- Markdown setup ----------------
     Written so it works with the marked 12 renderer API (positional args)
     and with newer versions (token object).                                  */
  marked.use({
    gfm: true,
    breaks: false,
    renderer: {
      code: function (a, b) {
        var code = typeof a === "object" ? a.text : a;
        var info = ((typeof a === "object" ? a.lang : b) || "").trim();
        var words = info.split(/\s+/);
        if (words[0] === "diagram") return diagramHtml(code);
        var fname = words.slice(1).join(" ");
        return (fname ? '<div class="fname">' + escapeHtml(fname) + "</div>\n" : "") +
          "<pre><code>" + escapeCode(code.replace(/\n$/, "")) + "</code></pre>\n";
      }
    }
  });

  /* ---------------- ::: containers ----------------
     Turned into plain HTML wrappers with blank lines around the body, so the
     markdown inside is still parsed normally by marked.                      */
  function expandContainers(md) {
    var lines = md.split("\n"), out = [], fence = null, stack = [];

    lines.forEach(function (line) {
      var f = line.match(/^ {0,3}(`{3,}|~{3,})/);
      if (fence) {
        if (f && f[1][0] === fence[0] && f[1].length >= fence.length && /^ {0,3}(`+|~+)\s*$/.test(line)) fence = null;
        out.push(line);
        return;
      }
      if (f) { fence = f[1]; out.push(line); return; }

      var open = line.match(/^:::\s*([a-z-]+)\s*(.*?)\s*$/i);
      if (open) {
        var kind = open[1].toLowerCase(), arg = open[2], html, close;
        if (kind === "qa") {
          html = '<details class="qa"><summary>' + marked.parseInline(arg) + "</summary><div>";
          close = "</div></details>";
        } else if (kind === "gaps") {
          html = '<div class="gaps">'; close = "</div>";
        } else if (kind === "note") {
          html = '<div data-block="note">'; close = "</div>";
        } else if (kind === "table") {
          html = '<div data-block="table" data-opts="' + escapeHtml(arg) + '">'; close = "</div>";
        } else {
          console.warn("Unknown ::: block:", kind);
          out.push(line);
          return;
        }
        out.push(html, "");
        stack.push(close);
        return;
      }
      if (/^:::\s*$/.test(line) && stack.length) {
        out.push("", stack.pop(), "");
        return;
      }
      out.push(line);
    });

    while (stack.length) out.push("", stack.pop(), ""); // unclosed block: close it
    return out.join("\n");
  }

  /* ---------------- DOM pass over the rendered markdown ---------------- */
  function postProcess(box) {
    // headings: ids from {#id} or from the text; h5 becomes the small label
    var used = {};
    box.querySelectorAll("h2, h3").forEach(function (h) {
      var custom = null;
      h.innerHTML = h.innerHTML.replace(/\s*\{#([\w-]+)\}\s*$/, function (_, id) { custom = id; return ""; });
      var id = custom || slugify(h.textContent), unique = id, n = 2;
      while (used[unique]) unique = id + "-" + n++;
      used[unique] = true;
      h.id = unique;
    });
    box.querySelectorAll("h5").forEach(function (h) {
      var p = document.createElement("p");
      p.className = "label";
      p.innerHTML = h.innerHTML;
      h.replaceWith(p);
    });

    box.querySelectorAll("ol").forEach(function (ol) { ol.classList.add("flow"); });

    box.querySelectorAll("strong").forEach(function (s) {
      var b = document.createElement("b");
      b.innerHTML = s.innerHTML;
      s.replaceWith(b);
    });

    box.querySelectorAll('a[href^="http"]').forEach(function (a) {
      a.target = "_blank";
      a.rel = "noopener noreferrer";
    });

    box.querySelectorAll('[data-block="note"]').forEach(function (div) {
      var kids = Array.prototype.slice.call(div.children);
      kids.forEach(function (k) { if (k.tagName === "P") k.classList.add("note"); });
      div.replaceWith.apply(div, kids);
    });

    // tables: always scrollable inside .tablewrap; optional class + column widths
    box.querySelectorAll('[data-block="table"]').forEach(function (div) {
      var opts = (div.getAttribute("data-opts") || "").split(/\s+/).filter(Boolean);
      var table = div.querySelector("table");
      div.removeAttribute("data-block");
      div.removeAttribute("data-opts");
      div.className = "tablewrap";
      if (!table) return;
      var widths = [];
      opts.forEach(function (o) {
        if (/%$/.test(o)) widths.push(o);
        else table.classList.add(o);
      });
      table.querySelectorAll("thead th").forEach(function (th, i) {
        if (widths[i]) th.style.width = widths[i];
      });
    });
    box.querySelectorAll("table").forEach(function (table) {
      if (table.parentElement.classList.contains("tablewrap")) return;
      var wrap = document.createElement("div");
      wrap.className = "tablewrap";
      table.replaceWith(wrap);
      wrap.appendChild(table);
    });
  }

  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }

  function buildHeader(meta) {
    var header = el("header");
    header.appendChild(el("h1", null, meta.title || "Untitled"));
    if (meta.tagline) header.appendChild(el("p", "tagline", meta.tagline));
    if (meta.author) {
      var by = el("p", "byline", "Author: ");
      if (meta.author_url) {
        var a = el("a", null, meta.author);
        a.href = meta.author_url; a.target = "_blank"; a.rel = "noopener";
        by.appendChild(a);
      } else {
        by.appendChild(document.createTextNode(meta.author));
      }
      header.appendChild(by);
    }
    if (meta.stack) header.appendChild(el("p", "byline", meta.stack));
    return header;
  }

  function buildToc(box) {
    var heads = box.querySelectorAll("h2");
    if (!heads.length) return null;
    var nav = el("nav", "toc");
    nav.setAttribute("aria-label", "Contents");
    nav.appendChild(el("p", null, "Contents"));
    var ol = el("ol");
    heads.forEach(function (h) {
      var li = el("li"), a = el("a", null, h.textContent);
      a.href = "#" + h.id;
      li.appendChild(a);
      ol.appendChild(li);
    });
    nav.appendChild(ol);
    return nav;
  }

  /* ---------------- Cover painting + back-to-top ---------------- */
  function initCover(meta) {
    var cover = document.getElementById("cover-img");
    if (!cover || !meta.cover) return;
    var f = meta.cover, urls;
    if (/^https?:\/\//.test(f) || f.charAt(0) === "/") {
      urls = [f];
    } else {
      var base = "https://commons.wikimedia.org/wiki/Special:FilePath/" + f;
      urls = [base + "?width=1280", base + "?width=1024", base + "?width=800"];
    }
    cover.style.backgroundPosition = meta.cover_position || "center 40%";
    (function next(i) {
      if (i >= urls.length) return;
      var im = new Image();
      im.referrerPolicy = "no-referrer";
      im.onload = function () {
        cover.style.backgroundImage = 'url("' + urls[i] + '")';
        cover.className += " on";
      };
      im.onerror = function () { next(i + 1); };
      im.src = urls[i];
    })(0);
  }

  function initToTop() {
    var btn = document.getElementById("to-top");
    if (!btn) return;
    function toggle() {
      btn.classList[(window.pageYOffset || document.documentElement.scrollTop) > 400 ? "add" : "remove"]("show");
    }
    window.addEventListener("scroll", toggle, { passive: true });
    toggle();
    btn.addEventListener("click", function () {
      var reduce = window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches;
      window.scrollTo({ top: 0, behavior: reduce ? "auto" : "smooth" });
    });
  }

  /* ---------------- Main ---------------- */
  async function init() {
    var root = document.getElementById("project-root");
    var loading = document.getElementById("loading");
    var slug = getSlug();

    initToTop();

    if (!slug) { loading.textContent = "No project specified."; return; }

    var raw;
    try {
      var res = await fetch(PROJECTS_DIR + slug + "/index.md");
      if (!res.ok) throw new Error(res.status);
      raw = await res.text();
    } catch (err) {
      loading.textContent = "Couldn't load this project. It may have been moved or renamed.";
      return;
    }

    var parsed = parseFrontmatter(raw), meta = parsed.meta;
    document.title = meta.page_title || (meta.title || "Untitled") + " | " + SITE_NAME;

    diagrams = [];
    var box = document.createElement("div");
    box.innerHTML = marked.parse(expandContainers(parsed.body));
    postProcess(box);

    root.textContent = "";
    root.appendChild(buildHeader(meta));
    var toc = buildToc(box);
    if (toc) root.appendChild(toc);
    while (box.firstChild) root.appendChild(box.firstChild);

    diagrams.forEach(function (d) {
      try {
        var spec = new Function("return (" + d.spec + "\n);")();
        window.D(d.id, d.w, d.h, spec);
      } catch (err) {
        console.error("Diagram " + d.id + " failed:", err);
      }
    });

    initCover(meta);

    // the page was empty on load, so jump to a #hash target once it exists
    if (window.location.hash) {
      var target = document.getElementById(decodeURIComponent(window.location.hash.slice(1)));
      if (target) window.scrollTo({ top: target.getBoundingClientRect().top + window.pageYOffset, behavior: "instant" });
    }
  }

  init();
})();
